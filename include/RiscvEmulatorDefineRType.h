#ifndef RiscvEmulatorDefineRType_H_
#define RiscvEmulatorDefineRType_H_

#include "RiscvEmulatorConfig.h"

// R-type, register register.

#define FUNCT7_FUNCT3_OPERATION_ADD  0b0000000000
#define FUNCT7_FUNCT3_OPERATION_SUB  0b0100000000
#define FUNCT7_FUNCT3_OPERATION_SLL  0b0000000001
#define FUNCT7_FUNCT3_OPERATION_SLT  0b0000000010
#define FUNCT7_FUNCT3_OPERATION_SLTU 0b0000000011
#define FUNCT7_FUNCT3_OPERATION_XOR  0b0000000100
#define FUNCT7_FUNCT3_OPERATION_SRL  0b0000000101
#define FUNCT7_FUNCT3_OPERATION_SRA  0b0100000101
#define FUNCT7_FUNCT3_OPERATION_OR   0b0000000110
#define FUNCT7_FUNCT3_OPERATION_AND  0b0000000111

#if (RVE_E_ZMMUL == 1)
#define FUNCT7_FUNCT3_OPERATION_MUL    0b0000001000
#define FUNCT7_FUNCT3_OPERATION_MULH   0b0000001001
#define FUNCT7_FUNCT3_OPERATION_MULHSU 0b0000001010
#define FUNCT7_FUNCT3_OPERATION_MULHU  0b0000001011
#endif
#if (RVE_E_M == 1)
#define FUNCT7_FUNCT3_OPERATION_DIV    0b0000001100
#define FUNCT7_FUNCT3_OPERATION_DIVU   0b0000001101
#define FUNCT7_FUNCT3_OPERATION_REM    0b0000001110
#define FUNCT7_FUNCT3_OPERATION_REMU   0b0000001111
#endif

#if (RVE_E_ZAAMO == 1)
#define FUNCT5_FUNCT3_OPERATION_AMOADD_W  0b00000010
#define FUNCT5_FUNCT3_OPERATION_AMOSWAP_W 0b00001010
#define FUNCT5_FUNCT3_OPERATION_AMOXOR_W  0b00100010
#define FUNCT5_FUNCT3_OPERATION_AMOOR_W   0b01000010
#define FUNCT5_FUNCT3_OPERATION_AMOAND_W  0b01100010
#define FUNCT5_FUNCT3_OPERATION_AMOMIN_W  0b10000010
#define FUNCT5_FUNCT3_OPERATION_AMOMAX_W  0b10100010
#define FUNCT5_FUNCT3_OPERATION_AMOMINU_W 0b11000010
#define FUNCT5_FUNCT3_OPERATION_AMOMAXU_W 0b11100010
#endif

#if (RVE_E_ZALRSC == 1)
#define FUNCT5_FUNCT3_OPERATION_LR_W 0b00010010
#define FUNCT5_FUNCT3_OPERATION_SC_W 0b00011010
#endif

#if (RVE_E_ZBA == 1)
#define FUNCT7_FUNCT3_OPERATION_SH1ADD 0b0010000010
#define FUNCT7_FUNCT3_OPERATION_SH2ADD 0b0010000100
#define FUNCT7_FUNCT3_OPERATION_SH3ADD 0b0010000110
#endif

#if (RVE_E_ZBB == 1)
#define FUNCT7_FUNCT3_OPERATION_ANDN 0b0100000111
#define FUNCT7_FUNCT3_OPERATION_ORN  0b0100000110
#define FUNCT7_FUNCT3_OPERATION_XNOR 0b0100000100
#define FUNCT7_FUNCT3_OPERATION_MAX  0b0000101110
#define FUNCT7_FUNCT3_OPERATION_MAXU 0b0000101111
#define FUNCT7_FUNCT3_OPERATION_MIN  0b0000101100
#define FUNCT7_FUNCT3_OPERATION_MINU 0b0000101101
#define FUNCT7_FUNCT3_OPERATION_ROL  0b0110000001
#define FUNCT7_FUNCT3_OPERATION_ROR  0b0110000101

#define FUNCT7_RS2_FUNCT3_OPERATION_ZEXTH 0b000010000000100
#endif

#if ((RVE_E_ZBC == 1) || (RVE_E_ZBKC == 1))
#define FUNCT7_FUNCT3_OPERATION_CMUL  0b0000101001
#define FUNCT7_FUNCT3_OPERATION_CMULH 0b0000101011
#endif
#if (RVE_E_ZBC == 1)
#define FUNCT7_FUNCT3_OPERATION_CMULR 0b0000101010
#endif

#if (RVE_E_ZBS == 1)
#define FUNCT7_FUNCT3_OPERATION_BCLR 0b0100100001
#define FUNCT7_FUNCT3_OPERATION_BEXT 0b0100100101
#define FUNCT7_FUNCT3_OPERATION_BINV 0b0110100001
#define FUNCT7_FUNCT3_OPERATION_BSET 0b0010100001
#endif

#if (RVE_E_ZBKB == 1)
#define FUNCT7_FUNCT3_OPERATION_PACK  0b0000100100
#define FUNCT7_FUNCT3_OPERATION_PACKH 0b0000100111
#endif

#if (RVE_E_ZBKX == 1)
#define FUNCT7_FUNCT3_OPERATION_XPERM8 0b0010100100
#define FUNCT7_FUNCT3_OPERATION_XPERM4 0b0010100010
#endif

#if (RVE_E_ZICOND == 1)
#define FUNCT7_FUNCT3_OPERATION_CZEROEQZ 0b0000111101
#define FUNCT7_FUNCT3_OPERATION_CZERONEZ 0b0000111111
#endif

#if (RVE_E_ZIHINTNTL == 1)
// The ntl instructions are encoded as add x0, x0, x2/x3/x4/x5. They share
// their funct7 and funct3 with ADD and are told apart by their rs2 field.
#define FUNCT7_FUNCT3_RS2_NTL_P1   0b00010
#define FUNCT7_FUNCT3_RS2_NTL_PALL 0b00011
#define FUNCT7_FUNCT3_RS2_NTL_S1   0b00100
#define FUNCT7_FUNCT3_RS2_NTL_ALL  0b00101
#endif

#endif